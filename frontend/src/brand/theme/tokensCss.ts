import {
  blur,
  breakpoints,
  cssName,
  font,
  gridColumns,
  isColorValue,
  leading,
  lineWidth,
  modes,
  opacity,
  radius,
  radiusBase,
  shadow,
  size,
  space,
  stroke,
  tracking,
  type,
  type ColorTree,
  type ColorValue,
  type TypeRole,
} from "./tokens";

/**
 * Writes `tokens.gen.css` from `tokens.ts`. `npm run gen:tokens` runs it, and
 * `npm run check:tokens` fails if the file on disk is not what it would write.
 *
 * Semantic colours sit on `:root` with their palette values resolved (only the
 * ones that change are repeated on `:root.dark`), measures sit on `:root` as
 * `--brand-*`, and `@theme inline` points each Tailwind namespace at them.
 * Inline keeps the `var()` live, so a utility follows the dark override; plain
 * `@theme` would bake in the light value.
 */

type Measure = number | string;
type Group = Record<string, Measure>;

const HEADER = `/* Generated by \`npm run gen:tokens\` from tokens.ts. Do not edit by hand. */`;

/** Every leaf of a colour tree as [CSS name, value], in the order written. */
function flatten(tree: ColorTree, path: string[] = []): [string, ColorValue][] {
  return Object.entries(tree).flatMap(([key, value]) =>
    isColorValue(value) ? [[cssName([...path, key]), value] as [string, ColorValue]] : flatten(value, [...path, key]),
  );
}

function rgb(hex: string): string {
  const digits = /^#([0-9a-f]{6})$/i.exec(hex)?.[1];
  if (!digits) throw new Error(`${hex} is not a six-digit hex colour`);
  return [0, 2, 4].map((i) => parseInt(digits.slice(i, i + 2), 16)).join(" ");
}

function colorCss(value: ColorValue): string {
  if (typeof value === "string") return value;
  if ("alias" in value) return `var(--${value.alias})`;
  if ("alpha" in value) return `rgb(${rgb(value.alpha[0])} / ${value.alpha[1]})`;
  const [base, over, percent] = value.mix;
  return `color-mix(in oklch, var(--${base}), var(--${over}) ${percent}%)`;
}

const withUnit = (unit: string) => (value: Measure) => (typeof value === "number" ? `${value}${unit}` : value);
const pixels = withUnit("px");
const unitless = withUnit("");

/** A token group as `--brand-<prefix>-<key>` on `:root`, and `--<theme>-<key>` in `@theme inline`. */
interface Section {
  group: Group;
  prefix: string;
  theme: string;
  format: (value: Measure) => string;
}

/** Each type role's size; the rest of the role is added in `@theme inline` below. */
const typeSizes: Group = Object.fromEntries(Object.entries(type).map(([role, { size }]) => [role, size]));

const SECTIONS: Section[] = [
  { group: font, prefix: "font", theme: "font", format: unitless },
  { group: typeSizes, prefix: "text", theme: "text", format: pixels },
  { group: leading, prefix: "leading", theme: "leading", format: unitless },
  { group: tracking, prefix: "tracking", theme: "tracking", format: pixels },
  { group: radius, prefix: "radius", theme: "radius", format: pixels },
  { group: space, prefix: "space", theme: "spacing", format: pixels },
  { group: size, prefix: "size", theme: "spacing", format: pixels },
  { group: stroke, prefix: "stroke", theme: "stroke-width", format: unitless },
  { group: opacity, prefix: "opacity", theme: "opacity", format: unitless },
];

/** The Tailwind colour a token gives: `score-birdie-text` is `text-score-birdie`. */
function colorUtility(name: string): string | null {
  // --shadow feeds the shadow-* values below; as a colour it would claim `text-shadow`.
  if (name === "shadow") return null;
  return name.replace(/^(score-\w+)-text$/, "$1");
}

const block = (selector: string, lines: string[]) => `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}`;

export function renderTokensCss(): string {
  const light = flatten(modes.light);
  const dark = new Map(flatten(modes.dark));
  const names = new Set(light.map(([name]) => name));
  for (const [name, value] of [...light, ...dark]) {
    const refs = typeof value !== "object" ? [] : "alias" in value ? [value.alias] : "mix" in value ? value.mix.slice(0, 2) : [];
    for (const ref of refs) {
      if (!names.has(String(ref))) throw new Error(`--${name} refers to --${ref}, which tokens.ts does not define`);
    }
  }

  const root = [
    ...light.map(([name, value]) => `--${name}: ${colorCss(value)};`),
    `--radius: ${radiusBase};`,
    ...SECTIONS.flatMap(({ group, prefix, format }) =>
      Object.entries(group).map(([key, value]) => `--brand-${prefix}-${key}: ${format(value)};`),
    ),
    `--brand-ring-width: ${pixels(lineWidth.ring)};`,
  ];

  const darkLines = light
    .filter(([name, value]) => JSON.stringify(dark.get(name)) !== JSON.stringify(value))
    .map(([name]) => `--${name}: ${colorCss(dark.get(name)!)};`);

  const theme = [
    ...Object.entries(breakpoints).map(([key, rem]) => `--breakpoint-${key}: ${rem}rem;`),
    ...light.flatMap(([name]) => {
      const utility = colorUtility(name);
      return utility ? [`--color-${utility}: var(--${name});`] : [];
    }),
    ...Object.entries(shadow).map(([key, value]) => `--shadow-${key}: ${value};`),
    ...SECTIONS.flatMap(({ group, prefix, theme }) =>
      Object.keys(group).map((key) => `--${theme}-${key}: var(--brand-${prefix}-${key});`),
    ),
    // A role's weight, tracking and line height ride on its text-* utility.
    ...Object.entries(type).flatMap(([role, spec]: [string, TypeRole]) => [
      ...(spec.weight != null ? [`--text-${role}--font-weight: ${spec.weight};`] : []),
      ...(spec.tracking != null ? [`--text-${role}--letter-spacing: ${pixels(spec.tracking)};`] : []),
      ...(spec.leading != null ? [`--text-${role}--line-height: ${spec.leading};`] : []),
    ]),
    ...Object.entries(blur).map(([key, value]) => `--blur-${key}: ${pixels(value)};`),
    `--ring-width-3: var(--brand-ring-width);`,
    ...Object.entries(gridColumns).map(([key, value]) => `--grid-template-columns-${key}: ${value};`),
  ];

  return [HEADER, block(":root", root), block(":root.dark", darkLines), block("@theme inline", theme)].join("\n\n") + "\n";
}
